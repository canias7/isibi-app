/** Routes that belong to the surface rather than to any one method. */
export const SHARED_ROUTES = ["methods", "identities", "identities/unlink", "sessions", "sessions/revoke"];

export const METHOD_NAMES = METHODS.map((m) => m.name);

export function methodByName(name) {
  const n = String(name == null ? "" : name).trim().toLowerCase();
  return METHODS.find((m) => m.name === n) || null;
}

/**
 * What this site offers, for the sign-in page to render.
 *
 * Second factors are deliberately NOT listed: they are not a way in, and showing
 * "Authenticator app" as a sign-in button would be a promise the flow cannot
 * keep. They surface in account settings instead.
 */
export function availableMethods(site = {}) {
  return METHODS
    .filter((m) => m.kind === "primary" && m.configured(site))
    .map((m) => ({
      name: m.name,
      label: (site.oauth && site.oauth[m.name] && site.oauth[m.name].label) || m.label,
      oauth: !!m.oauth,
    }));
}

/** Every sub-route the registry claims, so the router can be driven by it. */
export function methodRoutes() {
  const out = new Set(SHARED_ROUTES);
  for (const m of METHODS) for (const r of (m.routes || [])) out.add(r);
  return [...out];
}

/**
 * Is this path one of ours, and which method owns it?
 *
 * Matched against the registry rather than a regex full of method names, so
 * adding a method cannot leave a route unrouted or a router entry orphaned.
 */
export function routeFor(path) {
  const p = String(path == null ? "" : path).replace(/^\/+|\/+$/g, "").toLowerCase();
  if (SHARED_ROUTES.includes(p)) return { method: null, route: p };
  for (const m of METHODS) {
    for (const r of (m.routes || [])) if (r === p) return { method: m, route: p };
  }
  return null;
}

/**
 * A second factor is required to finish a sign-in when the account enabled one.
 *
 * Returned as a PENDING result rather than a session — the caller mints a
 * short-lived token that is good for exactly one thing (presenting the second
 * factor) and for nothing else. Handing back a real session here and "checking
 * 2FA on the next request" is the classic way a second factor becomes optional.
 */
export function secondFactorRequired(user) {
  return !!(user && user.totp_enabled);
}
