// The registry of ways to sign in.
//
// Built to be ADDED TO. Every method below is one entry describing what it
// needs, what it stores and which sub-routes it answers; the router walks this
// list rather than naming methods, so a new one is a new entry plus a handler
// and touches nothing else. The things that used to have to be edited in five
// places — the route matcher, the "what does this site offer" response, the
// owner's settings page, the storage migration, the client — all read from here.
//
// Two kinds, and the distinction is load bearing:
//
//   primary       proves who you are from nothing. password, google, passkey,
//                 email code. Ends in a session.
//   second        proves you still hold something, AFTER a primary. totp,
//                 recovery. Never ends in a session on its own.
//
// A method that got that wrong — a second factor that could mint a session by
// itself — would be a complete bypass of the first one.

import { PROVIDERS, PROVIDER_NAMES } from "./site-oauth.mjs";

/**
 * The device list, kept separate from the rest of `AUTH_DDL` because it is the
 * one internal table BOTH auth surfaces read.
 *
 * `AUTH_DDL` is applied only on the routes the registry owns — passkeys, OAuth,
 * emailed codes. Plain email-and-password sign-in never goes near it, and it now
 * joins `_sessions` on every authenticated request. A table that exists only on
 * sites where somebody happened to use a passkey would make `me` answer 500
 * everywhere else, which is precisely how login broke last time. Defined once
 * and run from both `AUTH_DDL` and `ensureSiteUsers`.
 */
export const SESSION_DDL = [
  // One row per signed-in device, so a member can see where they are signed in
  // and drop ONE. Sessions are still verified by their signature; this row only
  // answers "has this one been revoked", and it is read on the same statement as
  // the `_users` row rather than a second round trip.
  //
  // `revoked` is a flag and nothing ever deletes a row to revoke it: a missing
  // row reads as LIVE (see `sessionUsable`), so deleting would UN-revoke. The
  // sweeper only removes rows older than twice a token's life, by which point
  // the signature layer has been refusing them for a month.
  //
  // Times are BIGINT epoch seconds rather than the schema's TEXT timestamps —
  // they are only ever compared and subtracted, same as the lockout columns.
  `CREATE TABLE IF NOT EXISTS _sessions (
     sid TEXT PRIMARY KEY,
     user_id INTEGER NOT NULL,
     ua TEXT,
     country TEXT,
     created_at BIGINT,
     last_seen BIGINT,
     revoked INTEGER DEFAULT 0)`,
  `CREATE INDEX IF NOT EXISTS _sessions_user ON _sessions (user_id)`,
];

/** Tables a site needs before any of this works. Applied lazily, idempotently. */
export const AUTH_DDL = [
  ...SESSION_DDL,
  // One row per external identity. UNIQUE on (provider, subject) is the whole
  // integrity story: it is what stops two accounts claiming one Google user.
  `CREATE TABLE IF NOT EXISTS _identities (
     id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     provider TEXT NOT NULL,
     subject TEXT NOT NULL,
     user_id INTEGER NOT NULL,
     email TEXT,
     created_at TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS')))`,
  `CREATE UNIQUE INDEX IF NOT EXISTS _identities_pair ON _identities (provider, subject)`,
  `CREATE INDEX IF NOT EXISTS _identities_user ON _identities (user_id)`,

  // One row per passkey. A person may have several — phone, laptop, hardware key
  // — and removing one must not lock them out of the others.
  `CREATE TABLE IF NOT EXISTS _credentials (
     id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     user_id INTEGER NOT NULL,
     cred_id TEXT NOT NULL,
     public_key TEXT NOT NULL,
     alg TEXT NOT NULL,
     sign_count INTEGER DEFAULT 0,
     label TEXT,
     created_at TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS')),
     last_used_at TEXT)`,
  `CREATE UNIQUE INDEX IF NOT EXISTS _credentials_cred ON _credentials (cred_id)`,
  `CREATE INDEX IF NOT EXISTS _credentials_user ON _credentials (user_id)`,

  // Short-lived challenges and emailed codes. One table, because both are
  // "a secret we issued, for one purpose, that expires and is used once".
  `CREATE TABLE IF NOT EXISTS _auth_codes (
     id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     kind TEXT NOT NULL,
     subject TEXT NOT NULL,
     code TEXT NOT NULL,
     attempts INTEGER DEFAULT 0,
     expires_at TEXT NOT NULL,
     created_at TEXT DEFAULT (to_char(now() AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS')))`,
  `CREATE INDEX IF NOT EXISTS _auth_codes_lookup ON _auth_codes (kind, subject)`,
];

/** Columns the second factors need on `_users`. Idempotent-by-catch, per site. */
export const AUTH_USER_COLUMNS = [
  "ALTER TABLE _users ADD COLUMN totp_secret TEXT",
  "ALTER TABLE _users ADD COLUMN totp_enabled INTEGER DEFAULT 0",
  // The last accepted TOTP step. Without it a code is replayable for its whole
  // ninety-second life by anyone who saw it.
  "ALTER TABLE _users ADD COLUMN totp_last_step BIGINT",
  "ALTER TABLE _users ADD COLUMN recovery_hashes TEXT",
];

