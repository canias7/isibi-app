// THE LIMITED LOGIN ON A REAL POSTGRESQL 16 (2026-10-26, `site-app-login.mjs`).
//
// The unit tests prove what the module SENDS; this proves what Postgres DOES
// with it. No Neon, no Supabase, no network beyond 127.0.0.1:
//   pg_ctlcluster 16 main start
//   node test/integration/local-pg-app-login.mjs
//
// It makes a throwaway database owned by a throwaway OWNER role that is not a
// superuser (CREATEROLE, as Neon's `neondb_owner` is), builds a table the way a
// site has one (RLS on, a visitor policy), runs the shipping statements on the
// owner's login, then connects AS THE LIMITED LOGIN and reads every answer for
// its SQLSTATE: rows read and written as the owner saw them; CREATE, DROP,
// ALTER, GRANT, CREATE ROLE and ALTER ROLE refused for privilege (42501), never
// for another reason. A table the owner makes afterwards is covered by the
// default privileges and `appRowPolicySql`. A second run is idempotent.
import { execFileSync } from "node:child_process";
import { appLoginStatements, appRoleCheckSql, appRoleProblems, appRoleName, appRowPolicySql, newAppPassword } from "../../site-app-login.mjs";

const DB = "site_applogin_" + process.pid;
const OWNER = "own_" + process.pid;
const OWNER_PW = newAppPassword();
const APP = appRoleName(DB);
const APP_PW = newAppPassword();

function asSuper(sql, db = "postgres") {
  return execFileSync("runuser", ["-u", "postgres", "--", "psql", "-X", "-q", "-v", "ON_ERROR_STOP=1", "-At", "-d", db, "-c", sql], { encoding: "utf8" });
}
/** Run one statement as `user` over TCP. `{ ok, out, code }`, the SQLSTATE read from VERBOSITY verbose. */
function as(user, pw, sql) {
  try {
    const out = execFileSync("psql", ["-X", "-q", "-v", "ON_ERROR_STOP=1", "-v", "VERBOSITY=verbose", "-At", "-h", "127.0.0.1", "-U", user, "-d", DB, "-c", sql],
      { encoding: "utf8", env: { ...process.env, PGPASSWORD: pw }, stdio: ["ignore", "pipe", "pipe"] });
    return { ok: true, out: out.trim() };
  } catch (e) {
    const err = String(e.stderr || "");
    const m = /ERROR:\s+([0-9A-Z]{5}):/.exec(err);
    return { ok: false, code: m ? m[1] : "", err: err.split(APP_PW).join("[pw]").split(OWNER_PW).join("[pw]").slice(0, 200) };
  }
}

let failed = 0, passed = 0;
function check(name, cond, detail = "") {
  if (cond) { passed++; console.log("ok   " + name); }
  else { failed++; console.log("FAIL " + name + (detail ? "  — " + detail : "")); }
}
const refused = (r) => !r.ok && r.code === "42501";

try {
  asSuper(`CREATE ROLE "${OWNER}" LOGIN CREATEROLE PASSWORD '${OWNER_PW}'`);
  asSuper(`CREATE DATABASE "${DB}" OWNER "${OWNER}"`);
  asSuper(`ALTER SCHEMA public OWNER TO "${OWNER}"`, DB);
  // A site's table as the engine leaves it: RLS on, a visitor-shaped policy for
  // another role (none applies to the limited login).
  asSuper(`CREATE ROLE anonymous NOLOGIN`, "postgres").toString?.();
} catch (e) {
  if (!/already exists/.test(String(e.stderr || e.message))) { console.error("setup failed:", String(e.stderr || e.message).slice(0, 300)); process.exit(1); }
}
try {
  const own = (sql) => { const r = as(OWNER, OWNER_PW, sql); if (!r.ok) throw new Error(sql.slice(0, 60) + " → " + r.code + " " + r.err); return r; };
  own(`CREATE TABLE bookings (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT, owner_id UUID)`);
  own(`INSERT INTO bookings (name) VALUES ('a'), ('b')`);
  own(`ALTER TABLE bookings ENABLE ROW LEVEL SECURITY`);
  own(`CREATE POLICY isibi_bookings_insert ON bookings FOR INSERT TO anonymous WITH CHECK (true)`);
  own(`CREATE TABLE _meta (k TEXT PRIMARY KEY, v TEXT)`);
  own(`CREATE FUNCTION add_one(n int) RETURNS int LANGUAGE sql AS $$ SELECT n + 1 $$`);
  own(`REVOKE EXECUTE ON FUNCTION add_one(int) FROM PUBLIC`);

  for (const s of appLoginStatements(DB, APP_PW)) own(s);
  const chk = own(`SELECT row_to_json(x) FROM (${appRoleCheckSql(DB)}) x`);
  check("the read-back passes", appRoleProblems(JSON.parse(chk.out)).length === 0, chk.out);

  const app = (sql) => as(APP, APP_PW, sql);
  check("reads every row (as the owner did)", app(`SELECT count(*) FROM bookings`).out === "2");
  check("inserts a row", app(`INSERT INTO bookings (name) VALUES ('c')`).ok);
  check("updates a row", app(`UPDATE bookings SET name = 'z' WHERE name = 'a' RETURNING id`).out !== "");
  check("deletes a row", app(`DELETE FROM bookings WHERE name = 'b' RETURNING id`).out !== "");
  check("writes _meta", app(`INSERT INTO _meta (k, v) VALUES ('x', '1') ON CONFLICT (k) DO UPDATE SET v = EXCLUDED.v`).ok);
  check("calls a function", app(`SELECT add_one(1)`).out === "2");

  check("CREATE TABLE refused (42501)", refused(app(`CREATE TABLE evil (id int)`)));
  check("CREATE TABLE IF NOT EXISTS on an existing table refused (42501)", refused(app(`CREATE TABLE IF NOT EXISTS _meta (k TEXT PRIMARY KEY, v TEXT)`)));
  check("DROP TABLE refused (42501)", refused(app(`DROP TABLE bookings`)));
  check("ALTER TABLE refused (42501)", refused(app(`ALTER TABLE bookings ADD COLUMN x int`)));
  check("disabling RLS refused (42501)", refused(app(`ALTER TABLE bookings DISABLE ROW LEVEL SECURITY`)));
  check("DROP POLICY refused (42501)", refused(app(`DROP POLICY gf_app_rows ON bookings`)));
  check("TRUNCATE refused (42501)", refused(app(`TRUNCATE bookings`)));
  // A GRANT by a role holding no grant option is only a WARNING in Postgres
  // ("no privileges were granted"), so the proof is that nothing changed.
  app(`GRANT SELECT ON bookings TO anonymous`);
  check("GRANT changes nothing", own(`SELECT has_table_privilege('anonymous', 'bookings', 'SELECT')`).out === "f");
  check("CREATE ROLE refused (42501)", refused(app(`CREATE ROLE evil2`)));
  check("ALTER ROLE BYPASSRLS refused (42501)", refused(app(`ALTER ROLE "${APP}" BYPASSRLS`)));
  check("CREATE FUNCTION refused (42501)", refused(app(`CREATE FUNCTION evil3() RETURNS int LANGUAGE sql AS $$ SELECT 1 $$`)));
  check("CREATE SCHEMA refused (42501)", refused(app(`CREATE SCHEMA evil4`)));

  // RLS STILL APPLIES: without the row policy the login sees nothing.
  own(`DROP POLICY gf_app_rows ON bookings`);
  check("RLS applies: no row policy, no rows", app(`SELECT count(*) FROM bookings`).out === "0");
  own(appRowPolicySql("bookings"));
  check("appRowPolicySql puts the access back", app(`SELECT count(*) FROM bookings`).out === "2");

  // A TABLE MADE LATER BY THE OWNER: default privileges + the per-table policy.
  own(`CREATE TABLE orders (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, total INT)`);
  own(`ALTER TABLE orders ENABLE ROW LEVEL SECURITY`);
  own(appRowPolicySql("orders"));
  check("a later table: insert with its identity", app(`INSERT INTO orders (total) VALUES (5) RETURNING id`).out === "1");
  check("a later table: read", app(`SELECT total FROM orders`).out === "5");
  check("a later table: still no DROP (42501)", refused(app(`DROP TABLE orders`)));

  // IDEMPOTENT: the same statements again, with a new password.
  const pw2 = newAppPassword();
  let again = true;
  for (const s of appLoginStatements(DB, pw2)) { const r = as(OWNER, OWNER_PW, s); if (!r.ok) { again = false; console.log("  rerun:", r.code, r.err); } }
  check("a second run succeeds", again);
  check("a second run: the old password no longer works", !as(APP, APP_PW, `SELECT 1`).ok);
  check("a second run: rows still readable with the new one", as(APP, pw2, `SELECT count(*) FROM bookings`).out === "2");
  const policies = own(`SELECT count(*) FROM pg_policies WHERE policyname = 'gf_app_rows'`).out;
  check("a second run: one row policy per RLS table (2)", policies === "2", policies);
} catch (e) {
  failed++;
  console.log("FAIL setup: " + String(e.message).slice(0, 300));
} finally {
  try { asSuper(`DROP DATABASE IF EXISTS "${DB}"`); } catch { /* left for a manual drop */ }
  try { asSuper(`DROP ROLE IF EXISTS "${APP}"`); } catch { /* */ }
  try { asSuper(`DROP ROLE IF EXISTS "${OWNER}"`); } catch { /* */ }
}
console.log(`\n${passed} passed, ${failed} failed`);
process.exit(failed ? 1 : 0);
