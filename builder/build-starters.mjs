// build-starters.mjs — compiles builder/starters/<id>/** into builder/starters.data.mjs.
//
// Starters are AUTHORED as real files (`starters/booking/pages/Book.tsx`) so they typecheck against the real kit,
// render in the harness, and diff like code. They are CONSUMED as a data module, because the generation pipeline
// eventually ports into worker.js, which has no filesystem. Same split the capability registry already uses:
// author in a directory, generate a flat data file, commit both.
//
//   node builder/build-starters.mjs        # regenerate starters.data.mjs
//   node builder/build-starters.mjs --check  # fail if it is stale (CI)

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const SRC = path.join(here, 'starters')
const OUT = path.join(here, 'starters.data.mjs')

export function readStarters() {
  if (!fs.existsSync(SRC)) return {}
  const out = {}
  for (const id of fs.readdirSync(SRC).sort()) {
    const dir = path.join(SRC, id)
    if (!fs.statSync(dir).isDirectory()) continue
    const metaPath = path.join(dir, 'meta.json')
    if (!fs.existsSync(metaPath)) throw new Error(`starter "${id}" has no meta.json`)
    const meta = JSON.parse(fs.readFileSync(metaPath, 'utf8'))
    if (meta.id !== id) throw new Error(`starter "${id}" declares id "${meta.id}"`)

    const files = {}
    const pagesDir = path.join(dir, 'pages')
    if (!fs.existsSync(pagesDir)) throw new Error(`starter "${id}" has no pages/`)
    for (const f of fs.readdirSync(pagesDir).sort()) {
      if (!f.endsWith('.tsx')) continue
      // Authored at starters/<id>/pages/X.tsx, shipped at the path a generated app uses.
      files[`src/pages/${f}`] = fs.readFileSync(path.join(pagesDir, f), 'utf8')
    }
    // A starter may ship its own lib modules (a cart held in localStorage, a domain helper two pages share).
    // These land beside the template's own lib/, so a starter must not reuse a template filename.
    const libDir = path.join(dir, 'lib')
    if (fs.existsSync(libDir)) {
      for (const f of fs.readdirSync(libDir).sort()) {
        if (!/\.tsx?$/.test(f)) continue
        if (fs.existsSync(path.join(here, 'template/src/lib', f))) throw new Error(`starter "${id}" lib/${f} would overwrite the template's own lib file`)
        files[`src/lib/${f}`] = fs.readFileSync(path.join(libDir, f), 'utf8')
      }
    }

    const schema = path.join(dir, 'isibi.schema.json')
    if (fs.existsSync(schema)) files['isibi.schema.json'] = fs.readFileSync(schema, 'utf8')

    const pages = Object.keys(files)
      .map((p) => (p.match(/^src\/pages\/(\w+)\.tsx$/) || [])[1])
      .filter(Boolean)
    out[id] = { meta: { ...meta, pages }, files }
  }
  return out
}

function render(data) {
  return '// GENERATED by builder/build-starters.mjs from builder/starters/** — do not edit by hand.\n' +
    '// Run `node builder/build-starters.mjs` after changing any starter file.\n' +
    'export const STARTER_DATA = ' + JSON.stringify(data, null, 1) + ';\n'
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url))
if (isMain) {
  const data = readStarters()
  const next = render(data)
  const ids = Object.keys(data)
  const fileCount = ids.reduce((n, id) => n + Object.keys(data[id].files).length, 0)
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : ''
    if (cur !== next) {
      console.error('starters.data.mjs is STALE — run `node builder/build-starters.mjs` and commit the result')
      process.exit(1)
    }
    console.log(`starters.data.mjs is current — ${ids.length} starter(s), ${fileCount} files`)
  } else {
    fs.writeFileSync(OUT, next)
    console.log(`wrote starters.data.mjs — ${ids.length} starter(s) (${ids.join(', ')}), ${fileCount} files`)
  }
}
