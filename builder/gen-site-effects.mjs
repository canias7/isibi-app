// Copy the platform's follow-up modules into the site template (2026-10-27),
// so a site's own Worker runs the same code the platform ran: the owner's
// "new submission" email, the confirmation, the text and the webhook.
//
// Run `node builder/gen-site-effects.mjs` after touching any module below;
// test/site-effects-copy.test.mjs fails while a copy differs from its source.
// Each copy gets a `.d.mts` naming its exports, so the template's strict
// typecheck accepts the import without type-checking the module itself.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const EFFECT_MODULES = [
  "site-access.mjs", "site-row-effects.mjs", "site-notify.mjs", "site-mail.mjs",
  "site-sms.mjs", "site-webhooks.mjs", "site-ssrf.mjs", "site-providers.mjs",
];
export const EFFECTS_DIR = "builder/lovable/template/src/lib/effects";

export function exportsOf(src) {
  const names = new Set();
  for (const m of src.matchAll(/^export\s+(?:async\s+)?(?:function\*?|const|let|class)\s+([A-Za-z_$][\w$]*)/gm)) names.add(m[1]);
  return [...names].sort();
}

export function declarationOf(src) {
  return "// GENERATED by builder/gen-site-effects.mjs — do not edit by hand.\n" +
    exportsOf(src).map((n) => `export declare const ${n}: any;`).join("\n") + "\n";
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const dir = path.join(ROOT, EFFECTS_DIR);
  fs.mkdirSync(dir, { recursive: true });
  for (const f of EFFECT_MODULES) {
    const src = fs.readFileSync(path.join(ROOT, f), "utf8");
    fs.writeFileSync(path.join(dir, f), src);
    fs.writeFileSync(path.join(dir, f.replace(/\.mjs$/, ".d.mts")), declarationOf(src));
  }
  console.log("wrote", EFFECT_MODULES.length, "modules to", EFFECTS_DIR);
}
