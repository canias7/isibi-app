// Bakes each ready family's reference home page into a module the Worker can read.
//
// WHY THIS EXISTS AT ALL. The 100 reference apps under src/family-pages are the
// best pages in this repo — a real week grid, live availability, copy a business
// would actually write — and until 2026-08-04 the model had NEVER SEEN ONE and
// could not. A Worker has no filesystem, so the only things that reach the model
// are strings compiled into the bundle. Verified before writing this: nothing on
// the model path referenced src/family-pages, and PAGE_RULES never mentioned it.
//
// So the whole tier was in the shape this repo keeps rediscovering — on disk,
// typechecked, rendered, guarded, and reachable by nothing. The 27 blocks and the
// 196 examples were deleted for exactly that. These get wired instead, because
// unlike a block they are what a good site of that trade looks like.
//
// PAIRED WITH, NOT REPLACING, the barber exemplar in PAGE_RULES. The two answer
// different questions and neither substitutes for the other:
//   - Cutler Row Barbers (system block, cached) — how to CALL the API. Hooks,
//     form states, the four list states. Identical on every build, which is what
//     makes it free after the first one.
//   - the family page (user turn) — what a site of THIS TRADE should be. Varies
//     per build, so it can never live in the cached block: a cache entry is keyed
//     on the bytes, and a varying system block turns a $0.0082 read into a
//     $0.1019 write on every single build. Measured, not assumed.
//
// Run: node builder/gen-family-exemplars.mjs
import fs from "node:fs";
import path from "node:path";
import { READY_FAMILIES } from "./site-layouts.mjs";

const ROOT = path.join(import.meta.dirname, "..");
const PAGES = path.join(ROOT, "builder/lovable/template/src/family-pages");
const OUT = path.join(ROOT, "builder/family-exemplars.mjs");

// The reference pages carry long teaching comments — why the hero is what it is,
// which layout traps were hit. Those are for whoever maintains the app; the model
// is being shown the SHAPE, and it costs 5x to be shown prose it will not use.
// Blanked and collapsed rather than deleted line by line so nothing else shifts.
function stripComments(src) {
  return src
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/^[ \t]*\/\/[^\n]*\n/gm, "")
    .replace(/[ \t]+\/\/[^\n]*$/gm, "")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

const out = [];
const missing = [];
for (const family of READY_FAMILIES) {
  const file = path.join(PAGES, family, "index.tsx");
  if (!fs.existsSync(file)) { missing.push(family); continue; }
  out.push([family, stripComments(fs.readFileSync(file, "utf8"))]);
}

// A ready family with no reference page is a real gap, not something to paper
// over: the directive names its pages and there is no example behind them.
if (missing.length) {
  console.error(`no index.tsx for: ${missing.join(", ")}`);
  process.exitCode = 1;
}

const body = out
  .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
  .join("\n");

fs.writeFileSync(OUT, `// GENERATED by builder/gen-family-exemplars.mjs — do not edit by hand.
//
// One entry per ready family: its reference home page, comments stripped, as the
// worked example of what that trade's site should be. The Worker has no
// filesystem, so this module IS how those pages reach the model.
//
// Rides in the USER turn, never the cached system block — see the generator for
// the measurement.
export const FAMILY_EXEMPLARS = {
${body}
};
`);

const bytes = fs.statSync(OUT).size;
const chars = out.reduce((n, [, v]) => n + v.length, 0);
console.log(`${out.length} families → ${OUT}`);
console.log(`${(bytes / 1024).toFixed(0)} KB module · median exemplar ~${Math.round(
  out.map(([, v]) => v.length).sort((a, b) => a - b)[Math.floor(out.length / 2)] / 3.7,
)} tokens · ${(chars / 1024).toFixed(0)} KB of source`);
